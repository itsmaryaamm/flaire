#!/usr/bin/env node
/**
 * Flaire ↔ Shotoku sidecar.
 *
 * A tiny HTTP wrapper around the real `@shotoku/core` package (MIT, https://github.com/shotoku-dev/shotoku)
 * so the Python backend can use Shotoku's policy evaluation, hash-chained ledger and signed receipts
 * without re-implementing them. Nothing here holds money or keys.
 *
 *   POST /authorize  { company, policy, request }  -> AuthorizeResponse (+ receipt when approved)
 *   POST /approve    { company, decisionId, via }  -> ApprovalEntry
 *   POST /deny       { company, decisionId, via }  -> ApprovalEntry
 *   POST /receipt/verify { token, actor, resource, amount } -> { valid, reasons }
 *   GET  /health
 *
 * Each Flaire company gets its own policy.yaml and decisions.jsonl under DATA_DIR (default ./data).
 * The policy is regenerated by Flaire on every request from the agent's current permissions, so the
 * dashboard stays the single place where limits are edited.
 */
import http from "node:http";
import fs from "node:fs/promises";
import path from "node:path";
import { authorize, approve, deny, verifyReceipt, createReceipt } from "@shotoku/core";
import YAML from "yaml";

const PORT = Number(process.env.PORT ?? process.env.SHOTOKU_SERVICE_PORT ?? 8788);
const DATA_DIR = process.env.DATA_DIR ?? path.resolve("data");
const RECEIPT_SECRET = process.env.SHOTOKU_RECEIPT_SECRET ?? process.env.RECEIPT_SECRET ?? "flaire-dev-receipt-secret";
const RECEIPT_TTL = Number(process.env.RECEIPT_TTL_SECONDS ?? 300);

await fs.mkdir(DATA_DIR, { recursive: true });

const safe = (s) => String(s ?? "default").replace(/[^a-zA-Z0-9_-]/g, "_");
const policyPath = (company) => path.join(DATA_DIR, `policy-${safe(company)}.yaml`);
const ledgerPath = (company) => path.join(DATA_DIR, `decisions-${safe(company)}.jsonl`);

async function readJson(req) {
  let body = "";
  for await (const chunk of req) body += chunk;
  return body ? JSON.parse(body) : {};
}

function send(res, status, data) {
  res.writeHead(status, { "content-type": "application/json" });
  res.end(JSON.stringify(data));
}

const routes = {
  "POST /authorize": async ({ company, policy, request }) => {
    await fs.writeFile(policyPath(company), YAML.stringify(policy), "utf8");
    return authorize(request, {
      policyPath: policyPath(company),
      ledgerPath: ledgerPath(company),
      receiptSecret: RECEIPT_SECRET,
      receiptTtlSeconds: RECEIPT_TTL,
    });
  },
  "POST /approve": async ({ company, decisionId, via, receipt }) => {
    const entry = await approve(decisionId, { ledgerPath: ledgerPath(company), via });
    // Shotoku's ApprovalEntry carries no receipt; mint one for the approved action so the payment
    // service can verify it exactly like an auto-approval.
    const token = receipt
      ? createReceipt({ ...receipt, decisionId, secret: RECEIPT_SECRET, ttlSeconds: RECEIPT_TTL })
      : undefined;
    return { ...entry, receipt: token };
  },
  "POST /deny": async ({ company, decisionId, via }) => deny(decisionId, { ledgerPath: ledgerPath(company), via }),
  "POST /receipt/verify": async ({ token }) => verifyReceipt(token, { secret: RECEIPT_SECRET }),
  "GET /health": async () => ({ status: "ok", engine: "@shotoku/core", dataDir: DATA_DIR }),
};

http
  .createServer(async (req, res) => {
    const key = `${req.method} ${req.url.split("?")[0]}`;
    const handler = routes[key];
    if (!handler) return send(res, 404, { error: "not_found" });
    try {
      const body = req.method === "POST" ? await readJson(req) : {};
      send(res, 200, await handler(body));
    } catch (err) {
      // Fail closed: the Python side treats any error as "denied".
      send(res, 400, { error: "shotoku_error", message: err?.message ?? String(err) });
    }
  })
  .listen(PORT, () => process.stdout.write(`Flaire Shotoku sidecar on http://localhost:${PORT} (data: ${DATA_DIR})\n`));
